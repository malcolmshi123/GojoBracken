#requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $CandidateProject,
    [string] $UnityEditorPath = 'C:\Program Files\Unity 2022.3.62f2\Editor\Unity.exe',
    [string] $VoiceWav,
    [string] $VoiceCredits
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$withVoice = $PSBoundParameters.ContainsKey('VoiceWav') -or $PSBoundParameters.ContainsKey('VoiceCredits')
if ($withVoice) {
    if ([string]::IsNullOrWhiteSpace($VoiceWav) -or [string]::IsNullOrWhiteSpace($VoiceCredits)) {
        throw 'Supply both -VoiceWav and -VoiceCredits.'
    }
    if (-not (Test-Path -LiteralPath $VoiceWav -PathType Leaf) -or [IO.Path]::GetExtension($VoiceWav) -ne '.wav') {
        throw 'VoiceWav must point to a local WAV file.'
    }
    if (-not (Test-Path -LiteralPath $VoiceCredits -PathType Leaf) -or
        [string]::IsNullOrWhiteSpace((Get-Content -LiteralPath $VoiceCredits -Raw))) {
        throw 'VoiceCredits must point to a text file with source and permission details.'
    }
}
$project = (Resolve-Path -LiteralPath $CandidateProject).ProviderPath
if (-not (Test-Path -LiteralPath (Join-Path $project 'Assets\HdrpCandidates\Gojo.prefab'))) {
    throw 'Pass the u directory generated by Build-HdrpMaterials.ps1.'
}
$editor = Join-Path $project 'Assets\Editor'
New-Item -ItemType Directory -Path $editor -Force | Out-Null
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'hdrp\BuildSoloLiveTestBundle.cs') -Destination $editor -Force
$run = Split-Path -Parent $project
$log = Join-Path $run 'solo-live-bundle.log'
$arguments = @('-batchmode', '-quit', '-projectPath', ('"' + $project + '"'), '-force-d3d11',
    '-buildTarget', 'Win64', '-executeMethod', 'BuildSoloLiveTestBundle.Run', '-logFile', ('"' + $log + '"'))
$bundleFolder = 'live-test-bundle'
$stagedFiles = @()
try {
    if ($withVoice) {
        $bundleFolder = 'live-test-voice-bundle'
        $voiceId = [Guid]::NewGuid().ToString('N')
        $stem = Join-Path $project "Assets\GojoVoice-$voiceId"
        $stagedFiles = @("$stem.wav", "$stem.txt", "$stem.wav.meta", "$stem.txt.meta")
        Copy-Item -LiteralPath $VoiceWav -Destination "$stem.wav"
        Copy-Item -LiteralPath $VoiceCredits -Destination "$stem.txt"
        $arguments += @('-gojoVoiceId', $voiceId)
    }
    $process = Start-Process -FilePath $UnityEditorPath -ArgumentList $arguments -WindowStyle Hidden -Wait -PassThru
} finally {
    foreach ($file in $stagedFiles) {
        if (Test-Path -LiteralPath $file -PathType Leaf) { Remove-Item -LiteralPath $file }
    }
}
if ($process.ExitCode -ne 0 -or -not (Select-String -LiteralPath $log -SimpleMatch -Quiet -Pattern 'SOLO LIVE BUNDLE PASS:')) {
    throw "Solo live bundle build failed. Read $log."
}
Write-Output "Solo live bundle: $(Join-Path $run ($bundleFolder + '\gojobracken'))"
