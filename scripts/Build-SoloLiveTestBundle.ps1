#requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $CandidateProject,
    [string] $UnityEditorPath = 'C:\Program Files\Unity 2022.3.62f2\Editor\Unity.exe'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$project = (Resolve-Path -LiteralPath $CandidateProject).ProviderPath
if (-not (Test-Path -LiteralPath (Join-Path $project 'Assets\HdrpCandidates\Gojo.prefab'))) {
    throw 'Pass the u directory generated by Build-HdrpMaterials.ps1.'
}
$editor = Join-Path $project 'Assets\Editor'
New-Item -ItemType Directory -Path $editor -Force | Out-Null
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'hdrp\BuildSoloLiveTestBundle.cs') -Destination $editor -Force
$run = Split-Path -Parent $project
$log = Join-Path $run 'solo-live-bundle.log'
$arguments = @('-batchmode', '-quit', '-projectPath', ('"' + $project + '"'), '-force-d3d11',
    '-buildTarget', 'Win64', '-executeMethod', 'BuildSoloLiveTestBundle.Run', '-logFile', ('"' + $log + '"'))
$process = Start-Process -FilePath $UnityEditorPath -ArgumentList $arguments -WindowStyle Hidden -Wait -PassThru
if ($process.ExitCode -ne 0 -or -not (Select-String -LiteralPath $log -SimpleMatch -Quiet -Pattern 'SOLO LIVE BUNDLE PASS:')) {
    throw "Solo live bundle build failed. Read $log."
}
Write-Output "Solo live bundle: $(Join-Path $run 'live-test-bundle\gojobracken')"
