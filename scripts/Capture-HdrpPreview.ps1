#requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $CandidateProject,
    [string] $UnityEditorPath = 'C:\Program Files\Unity 2022.3.62f2\Editor\Unity.exe'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$project = (Resolve-Path -LiteralPath $CandidateProject).ProviderPath
if (-not (Test-Path -LiteralPath (Join-Path $project 'Assets\HdrpCandidates\Gojo.prefab')) -or
    -not (Test-Path -LiteralPath (Join-Path $project 'Assets\ValidationPipeline.asset'))) {
    throw 'Pass the u directory generated by Build-HdrpMaterials.ps1.'
}
$repo = Split-Path -Parent $PSScriptRoot
$capture = Join-Path $project 'Assets\HdrpCapture'
New-Item -ItemType Directory -Force $capture | Out-Null
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'hdrp\CaptureHdrpPreview.cs') -Destination $capture
foreach ($file in @('BrackenCosmeticController.cs', 'BrackenVisibilityReader.cs')) {
    Copy-Item -LiteralPath (Join-Path $repo ('src\GojoBracken\' + $file)) -Destination $capture
}
Copy-Item -Path (Join-Path $repo 'shared\GojoBracken.Presentation\Runtime\*.cs') -Destination $capture
$log = Join-Path (Split-Path -Parent $project) 'hdrp-capture.log'
$arguments = @('-batchmode', '-quit', '-projectPath', ('"' + $project + '"'), '-force-d3d11',
    '-executeMethod', 'GojoBracken.CaptureHdrpPreview.Run', '-logFile', ('"' + $log + '"'))
$process = Start-Process -FilePath $UnityEditorPath -ArgumentList $arguments -WindowStyle Hidden -Wait -PassThru
if ($process.ExitCode -ne 0 -or -not (Select-String -LiteralPath $log -SimpleMatch -Quiet -Pattern 'HDRP CAPTURE PASS:')) {
    throw "HDRP capture failed. Read $log."
}
Write-Output "HDRP captures: $(Join-Path (Split-Path -Parent $project) 'renders')"
